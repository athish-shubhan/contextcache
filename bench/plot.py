#!/usr/bin/env python3
"""results/*.json -> figures and results/SUMMARY.md for ContextCache."""
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

d = sys.argv[1]
J = lambda n: json.load(open(os.path.join(d, n + ".json"))) if os.path.exists(os.path.join(d, n + ".json")) else None
COL = {"bm25": "#9aa5b1", "trigram": "#e8a33d", "hybrid": "#2bb3a3", "dense": "#6a51a3", "hybrid+dense": "#c75b7a"}
md = ["# ContextCache results", "", "Generated by `bench/plot.py` from `results/*.json`. One 2-vCPU VM; no model was called anywhere.", ""]

ov = J("overload")
if ov:
    rows = ov["rows"]
    md += ["## 1. Tool overload: finding the right tool among N", "",
           f"BFCL catalog: {ov['tools']:,} tools; {ov['queries']:,} queries with exactly one correct tool. For each query, the correct tool plus N-1 random "
           "distractors. Recall@k = the correct tool is in the top k. Tokens are cl100k tokens of the tool definitions as sent to a model"
           f"{'' if ov['exact_tokenizer'] else ' (approximate: tokenizer unavailable)'}.", "",
           "| N tools | ranker | recall@1 | recall@3 | recall@5 | recall@10 | MRR | tokens, all N tools | tokens, top-5 schemas | tokens, search_tools result (k=5) + meta-tools |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['n_tools']:,} | {r['ranker']} | {100*r['recall_at']['1']:.1f}% | {100*r['recall_at']['3']:.1f}% | {100*r['recall_at']['5']:.1f}% | "
                  f"{100*r['recall_at']['10']:.1f}% | {r['mrr']:.3f} | {r['mean_tokens_all_tools']:,.0f} | {r['mean_tokens_top_k']['5']:,.0f} | "
                  f"{r['mean_tokens_search_result_k5'] + r['meta_tool_tokens']:,.0f} |")
    md.append("")
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.6))
    for rk in ["bm25", "trigram", "hybrid", "dense", "hybrid+dense"]:
        rs = [r for r in rows if r["ranker"] == rk]
        if not rs:
            continue
        axs[0].plot([r["n_tools"] for r in rs], [100 * r["recall_at"]["5"] for r in rs], "-o", color=COL[rk], label=f"{rk} recall@5")
        axs[0].plot([r["n_tools"] for r in rs], [100 * r["recall_at"]["1"] for r in rs], "--", color=COL[rk], alpha=0.7, label=f"{rk} recall@1")
    hy = [r for r in rows if r["ranker"] == "hybrid"]
    axs[1].plot([r["n_tools"] for r in hy], [r["mean_tokens_all_tools"] for r in hy], "-o", color="#c75b7a", label="all N tool schemas")
    axs[1].plot([r["n_tools"] for r in hy], [r["mean_tokens_top_k"]["5"] for r in hy], "-o", color="#2bb3a3", label="top-5 schemas")
    axs[1].plot([r["n_tools"] for r in hy], [r["mean_tokens_search_result_k5"] + r["meta_tool_tokens"] for r in hy], "-o", color="#5b8def", label="meta-tools + search result")
    for a in axs:
        a.set_xscale("log")
        a.set_xlabel("tools available (N)")
        a.spines[["top", "right"]].set_visible(False)
        a.legend(frameon=False, fontsize=7)
    axs[0].set_ylabel("%")
    axs[0].set_title("is the right tool retrieved?", fontsize=9)
    axs[1].set_yscale("log")
    axs[1].set_ylabel("prompt tokens per turn")
    axs[1].set_title("context cost of the tools", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(d, "overload.png"), dpi=150)

pv = J("pgvector")
if pv:
    md += ["### Dense retrieval in Postgres (pgvector, HNSW)", "",
           f"All {pv['tools']:,} tools embedded ({pv['dim']}-d GloVe, SIF weighting) and stored in Postgres with pgvector 0.6 and an HNSW index "
           f"(m = 16, ef_construction = 64, built in {pv['hnsw_build_sec']:.2f} s). Over {pv['queries']:,.0f} queries: the approximate top 10 shares "
           f"{100*pv['ann_top10_overlap_with_exact']:.1f}% of its entries with exact cosine search; recall@5 of the correct tool {100*pv['recall5_pgvector']:.1f}% "
           f"(exact: {100*pv['recall5_exact']:.1f}%); query latency p50 {pv['pgvector_ms']['p50']:.2f} ms, p99 {pv['pgvector_ms']['p99']:.2f} ms "
           f"(in-process brute force over 1,520 vectors: p50 {pv['in_memory_exact_ms']['p50']:.2f} ms).", ""]

sk = J("skills")
if sk:
    md += ["## 2. Skill triggering as the skill count grows", "",
           "Each catalog tool plays an Agent Skill (its name and description are the tier-1 text that is always in context). Relevant queries have one "
           "matching skill; BFCL irrelevance queries have none. The trigger loads the top skill when its trigram similarity clears a threshold chosen on a "
           f"training half at N = 100 (train F1 {sk['train_f1_at_100']:.3f}) and kept fixed. This is a retrieval trigger, not a model's decision.", "",
           "| skills | precision | recall | false triggers on irrelevant queries | tier-1 tokens for all skills |", "|---|---|---|---|---|"]
    for r in sk["rows"]:
        md.append(f"| {r['n_skills']:,} | {100*r['precision']:.1f}% | {100*r['recall']:.1f}% | {100*r['false_trigger_rate_irrelevant']:.1f}% | {r['tier1_tokens_all_descriptions']:,.0f} |")
    md.append("")

ca = J("cache")
if ca:
    rows = ca["rows"]
    md += ["## 3. Which tools stay loaded: retrieval and admission over a long session", "",
           f"{rows[0]['turns']:,} turns; each needs one tool (Zipf {ca['zipf']} popularity over {ca['tools_with_queries']:,} tools, popularity shifts every "
           f"{ca['shift_every']:,} turns) and carries one of that tool's real queries. Budget = tool-schema tokens allowed in context per turn "
           f"(all {ca['tools']:,} schemas would be {ca['all_tools_tokens']:,} tokens). Hit = the needed tool's schema was in context.", "",
           "| budget | strategy | hit rate | mean tool tokens in context |", "|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['budget_tokens']:,} | {r['strategy']} | {100*r['needed_tool_in_context']:.1f}% | {r['mean_tool_tokens_in_context']:,.0f} |")
    md.append("")
    fig, ax = plt.subplots(figsize=(6.5, 3.6))
    strats = []
    for r in rows:
        if r["strategy"] not in strats:
            strats.append(r["strategy"])
    cs = ["#9aa5b1", "#c9ced6", "#a7c0f5", "#5b8def", "#e8a33d", "#2bb3a3"]
    for s, c in zip(strats, cs):
        rs = [r for r in rows if r["strategy"] == s]
        ax.plot([r["budget_tokens"] for r in rs], [100 * r["needed_tool_in_context"] for r in rs], "-o", color=c, label=s, ms=4)
    ax.set_xscale("log", base=2)
    ax.set_xlabel("tool-schema token budget per turn")
    ax.set_ylabel("needed tool in context (%)")
    ax.legend(frameon=False, fontsize=7)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(os.path.join(d, "cache.png"), dpi=150)

la = J("latency")
if la:
    md += ["## 4. Gateway overhead", "",
           f"Stdio MCP everywhere; the gateway fronts {la['farms']} upstream servers. `tools/list` in all mode returns {la['tools_list_all_mode']['tools']:,} tools "
           f"({la['tools_list_all_mode']['tokens']:,} tokens); in meta mode {la['tools_list_meta_mode']['tools']} tools ({la['tools_list_meta_mode']['tokens']:,} tokens).", "",
           "| path | operation | concurrent callers | p50 | p99 |", "|---|---|---|---|---|"]
    for r in la["rows"]:
        md.append(f"| {r['path']} | {r['op']} | {r['concurrency']} | {r['p50_us']/1000:.2f} ms | {r['p99_us']/1000:.2f} ms |")
    dr = {(r["path"], r["concurrency"]): r for r in la["rows"] if r["op"] == "tools/call"}
    for c in [1, 8]:
        a, b = dr.get(("direct to one MCP server", c)), dr.get(("through gateway (all mode)", c))
        if a and b:
            md.append(f"\nAdded by the gateway at {c} concurrent caller(s): p50 {(b['p50_us']-a['p50_us'])/1000:+.2f} ms, p99 {(b['p99_us']-a['p99_us'])/1000:+.2f} ms.")
    md.append("")

mr = J("memrevise")
if mr:
    kinds = ["current", "deleted", "as_of", "as_recorded"]
    md += ["## 5. MemRevise", "",
           f"{mr['users']} users x {mr['events_per_user']:,} events ({', '.join(f'{k} {v:,}' for k, v in mr['events_by_op'].items())}); "
           f"{mr['queries']:,} queries ({', '.join(f'{k} {v}' for k, v in mr['queries_by_kind'].items())}). One user's history is about "
           f"{mr['history_tokens_per_user_median']:,.0f} tokens. Stores get structured payloads; no model reads anything.", "",
           "| store | overall | current | deleted (must answer NONE) | as of a past date | as recorded at a past date |", "|---|---|---|---|---|---|"]
    for s in mr["scores"]:
        b = s["accuracy_by_kind"]
        md.append(f"| {s['store']} | **{100*s['accuracy']:.1f}%** | " + " | ".join(f"{100*b.get(k, float('nan')):.1f}%" for k in kinds) + " |")
    if "postgres_latency_ms" in mr:
        p = mr["postgres_latency_ms"]
        md += ["", f"Postgres bi-temporal store, local Postgres 16: write (one transaction per fact change) p50 {p['write_p50']:.2f} ms, p99 {p['write_p99']:.2f} ms "
               f"over {p['writes']:,.0f} writes; read p50 {p['read_p50']:.2f} ms, p99 {p['read_p99']:.2f} ms over {p['reads']:,.0f} queries."]
    md.append("")

cf = J("conformance")
if cf:
    ok = sum(c["ok"] for c in cf["checks"])
    md += ["## 6. Conformance with the official MCP Python SDK", "", f"MCP Python SDK {cf['mcp_sdk_version']} as the client: {ok} of {len(cf['checks'])} checks pass.", "",
           "| check | result |", "|---|---|"]
    for c in cf["checks"]:
        md.append(f"| {c['check']} | {'pass' if c['ok'] else 'FAIL: ' + c['detail']} |")
    md.append("")

open(os.path.join(d, "SUMMARY.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))
